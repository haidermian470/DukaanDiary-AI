"""Generate SYNTHETIC payment screenshots for the screenshot-check demo.

They show references from the Dummy Bank seed data (DDB-100001 ...), are branded
"DukaanDiary Demo Bank" and carry a large DEMO banner. They are not real receipts.

Usage (from backend/, venv active, after `pip install -r requirements-dev.txt`):
    python -m scripts.make_demo_screenshots
Images are written to backend/demo_assets/.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent.parent / "demo_assets"

# file name, reference, amount, sender, status text, what the demo should show
SCREENSHOTS = [
    ("1_match.png", "DDB-100001", "2,000", "Ahmed Raza", "Successful", "Matches a demo bank record"),
    ("2_amount_changed.png", "DDB-100001", "20,000", "Ahmed Raza", "Successful", "Needs careful review"),
    ("3_pending.png", "DDB-100003", "1,500", "Sana Ahmed", "Processing", "Pending or delayed"),
    ("4_failed_but_shows_success.png", "DDB-100004", "4,200", "Usman Ali", "Successful", "Needs careful review"),
    ("5_delayed_transfer.png", "DDB-DELAY-01", "4,500", "Sana Ahmed", "Successful",
     "Could not verify -> simulate arrival -> matches"),
]


def font(size: int):
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # very old Pillow
        return ImageFont.load_default()


def draw_one(name, ref, amount, sender, status, _expected):
    img = Image.new("RGB", (720, 1000), "#F4F6F8")
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, 720, 120], fill="#1F4E79")
    d.text((40, 38), "DukaanDiary Demo Bank", fill="white", font=font(40))
    d.rectangle([0, 120, 720, 190], fill="#C62828")
    d.text((40, 136), "DEMO - SYNTHETIC - NOT A REAL PAYMENT", fill="white", font=font(30))
    d.rounded_rectangle([40, 230, 680, 900], radius=24, fill="white", outline="#D0D7DE", width=2)
    color = "#2E7D32" if status == "Successful" else "#EF6C00"
    d.text((80, 270), f"Transfer {status}", fill=color, font=font(44))
    d.text((80, 360), "Amount", fill="#57606A", font=font(28))
    d.text((80, 400), f"Rs {amount}", fill="#111111", font=font(64))
    rows = [("Transaction ID", ref), ("From", sender), ("To", "My Shop (DEMO)"), ("Channel", "IBFT (simulated)")]
    y = 520
    for label, value in rows:
        d.text((80, y), label, fill="#57606A", font=font(28))
        d.text((360, y), value, fill="#111111", font=font(30))
        y += 80
    d.text((40, 930), "Synthetic image for the DukaanDiary AI demo only.", fill="#C62828", font=font(24))
    img.save(OUT / name)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    lines = ["# Demo screenshots (SYNTHETIC)", "", "Generated by scripts/make_demo_screenshots.py.",
             "Seed the Dummy Bank first (GET /api/v1/dummy-bank/accounts).", "",
             "| File | Reference | Expected result |", "|---|---|---|"]
    for row in SCREENSHOTS:
        draw_one(*row)
        lines.append(f"| {row[0]} | {row[1]} | {row[5]} |")
    lines += ["", "For 5_delayed_transfer.png: check it once (not found), then call",
              "POST /api/v1/dummy-bank/simulate/incoming with amount 4500, counterparty_name \"Sana Ahmed\",",
              "reference DDB-DELAY-01, and check the same image again."]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(SCREENSHOTS)} images to {OUT}")


if __name__ == "__main__":
    main()
